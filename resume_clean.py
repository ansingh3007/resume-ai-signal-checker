#!/usr/bin/env python3
"""
resume_clean.py — Strip AI-tool metadata from .docx resumes and flag
statistical / stylistic "AI-generated" signals in the text (the kind of
signal ATS plugins and AI-detector heuristics actually key on).

There is no watermark to remove from resume text (no hidden token-sampling
signal). What actually gets flagged is:
  1. Document metadata ("Generated by ChatGPT", app name, etc.)
  2. AI-cliche phrasing (stock LLM-isms)
  3. Low "burstiness" — unnaturally uniform sentence length / structure
  4. Repetitive bullet openers (every bullet starting the same way)

Usage:
    python3 resume_clean.py inspect resume.docx
    python3 resume_clean.py clean   resume.docx -o resume.cleaned.docx
    python3 resume_clean.py inspect resume.txt
"""
import argparse
import io
import re
import statistics
import sys
import zipfile
from pathlib import Path
from xml.etree import ElementTree as ET

# ---------------------------------------------------------------------------
# 1. DOCX METADATA
# ---------------------------------------------------------------------------

CORE_NS = "http://schemas.openxmlcalendar/does-not-matter"  # placeholder, unused
DOCPROPS_CORE = "docProps/core.xml"
DOCPROPS_APP = "docProps/app.xml"
CUSTOM_XML_PREFIX = "customXml/"

# Namespaces used in docProps/core.xml
NS = {
    "cp": "http://schemas.openxmlformats.org/package/2006/metadata/core-properties",
    "dc": "http://purl.org/dc/elements/1.1/",
    "dcterms": "http://purl.org/dc/terms/",
    "xsi": "http://www.w3.org/2001/XMLSchema-instance",
}

# app/tool names that leak "this was AI-generated / AI-assisted" info
SUSPICIOUS_TOKENS = [
    "chatgpt", "openai", "gpt-", "gpt4", "gpt-4", "claude", "anthropic",
    "gemini", "bard", "copilot", "jasper", "rytr", "writesonic",
    "resumeworded", "kickresume ai", "teal ai", "rezi ai", "novoresume ai",
    "ai-generated", "generated by ai", "chat gpt",
]


def inspect_docx_metadata(path: Path) -> dict:
    report = {"core_props": {}, "app_props": {}, "suspicious_hits": [], "custom_xml_files": []}
    with zipfile.ZipFile(path) as z:
        names = z.namelist()

        if DOCPROPS_CORE in names:
            core_xml = z.read(DOCPROPS_CORE)
            root = ET.fromstring(core_xml)
            for child in root:
                tag = child.tag.split("}")[-1]
                report["core_props"][tag] = child.text or ""

        if DOCPROPS_APP in names:
            app_xml = z.read(DOCPROPS_APP)
            root = ET.fromstring(app_xml)
            for child in root:
                tag = child.tag.split("}")[-1]
                report["app_props"][tag] = child.text or ""

        report["custom_xml_files"] = [n for n in names if n.startswith(CUSTOM_XML_PREFIX)]

        all_text_blobs = list(report["core_props"].values()) + list(report["app_props"].values())
        for n in report["custom_xml_files"]:
            try:
                all_text_blobs.append(z.read(n).decode("utf-8", errors="ignore"))
            except Exception:
                pass

        haystack = " ".join(all_text_blobs).lower()
        for token in SUSPICIOUS_TOKENS:
            if token in haystack:
                report["suspicious_hits"].append(token)

    return report


def clean_docx_metadata(path: Path, out_path: Path) -> dict:
    """Blank out core/app properties that commonly carry tool/author fingerprints
    and strip customXml parts (often used by AI writing tools to tag output)."""
    removed = {"core_props_cleared": [], "app_props_cleared": [], "custom_xml_removed": []}

    with zipfile.ZipFile(path) as zin:
        names = zin.namelist()
        buf = io.BytesIO()
        with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zout:
            for item in zin.infolist():
                data = zin.read(item.filename)

                if item.filename == DOCPROPS_CORE:
                    root = ET.fromstring(data)
                    for child in list(root):
                        tag = child.tag.split("}")[-1]
                        # Keep title/language if meaningful; blank fingerprint-y fields
                        if tag in ("creator", "lastModifiedBy", "description", "keywords", "subject", "category"):
                            if child.text:
                                removed["core_props_cleared"].append(f"{tag}={child.text!r}")
                            child.text = ""
                    data = ET.tostring(root, encoding="utf-8", xml_declaration=True)

                elif item.filename == DOCPROPS_APP:
                    root = ET.fromstring(data)
                    for child in list(root):
                        tag = child.tag.split("}")[-1]
                        if tag in ("Application", "AppVersion", "Company", "Manager"):
                            if child.text:
                                removed["app_props_cleared"].append(f"{tag}={child.text!r}")
                            child.text = ""
                    data = ET.tostring(root, encoding="utf-8", xml_declaration=True)

                elif item.filename.startswith(CUSTOM_XML_PREFIX):
                    removed["custom_xml_removed"].append(item.filename)
                    continue  # drop entirely

                zout.writestr(item, data)

        out_path.write_bytes(buf.getvalue())

    return removed


# ---------------------------------------------------------------------------
# 2. TEXT EXTRACTION (docx -> plain bullets, or plain text file)
# ---------------------------------------------------------------------------

def extract_text_from_docx(path: Path) -> list[str]:
    lines = []
    with zipfile.ZipFile(path) as z:
        xml = z.read("word/document.xml")
    root = ET.fromstring(xml)
    w_ns = "{http://schemas.openxmlformats.org/wordprocessingml/2006/main}"
    for p in root.iter(f"{w_ns}p"):
        texts = [t.text or "" for t in p.iter(f"{w_ns}t")]
        line = "".join(texts).strip()
        if line:
            lines.append(line)
    return lines


def extract_text_from_plain(path: Path) -> list[str]:
    return [l.strip() for l in path.read_text(encoding="utf-8", errors="ignore").splitlines() if l.strip()]


