def cmd_inspect(args):
    path = Path(args.file)
    print(f"Inspecting: {path.name}\n")

    if path.suffix.lower() == ".docx":
        meta = inspect_docx_metadata(path)
        print("== DOCX metadata ==")
        for k, v in meta["core_props"].items():
            if v:
                print(f"  core.{k}: {v}")
        for k, v in meta["app_props"].items():
            if v:
                print(f"  app.{k}: {v}")
        if meta["custom_xml_files"]:
            print(f"  customXml parts present: {len(meta['custom_xml_files'])} (often used by writing tools)")
        if meta["suspicious_hits"]:
            print(f"  suspicious tokens found: {meta['suspicious_hits']}")
        else:
            print("  No AI-tool fingerprints found in metadata.")
        lines = extract_text_from_docx(path)
    else:
        lines = extract_text_from_plain(path)
        print("(plain text file — no document metadata to check)")

    print("\n== Text style signals ==")
    cliches = find_cliches(lines)
    if cliches:
        print(f"  {len(cliches)} AI-cliche phrase(s) found:")
        for phrase, examples in cliches.items():
            print(f"    - '{phrase}'  (e.g. \"{examples[0]}\")")
    else:
        print("  No stock AI-cliche phrases found.")

    openers = bullet_opener_repetition(lines)
    if openers:
        print(f"  Repeated bullet openers: {openers}")
    else:
        print("  Bullet openers look varied.")

    burst = burstiness_report(lines)
    print(f"  Sentence length variance: {burst}")
    if burst.get("low_variance_flag"):
        print("  Sentence lengths are unusually uniform — a common AI-text tell.")

    print("\n== Harvard FAS resume-guide checks ==")
    print("   (careerservices.fas.harvard.edu/resources/create-a-strong-resume)")
    pronoun_hits = harvard_pronoun_check(lines)
    if pronoun_hits:
        print(f"  Personal pronouns found ({len(pronoun_hits)}) — Harvard: \"Don't use personal pronouns (such as I or We)\":")
        for h in pronoun_hits[:10]:
            print(f"    - \"{h}\"")
    else:
        print("  No personal pronouns (I/We/My/Our) found — matches Harvard's guidance.")

    weak_openers = harvard_weak_opener_check(lines)
    if weak_openers:
        print(f"  {len(weak_openers)} bullet(s) open with a word not on Harvard's action-verb list:")
        for w in weak_openers[:15]:
            print(f"    - {w}")
    else:
        print("  Every bullet opens with a verb from Harvard's action-verb bank.")

    print("\nDone. This is heuristic, not a certified AI-detector result.")


def cmd_clean(args):
    path = Path(args.file)
    out_path = Path(args.output) if args.output else path.with_suffix(".cleaned.docx")

    if path.suffix.lower() != ".docx":
        print("clean mode only handles .docx metadata scrubbing; for .txt/.md just hand-edit the flagged lines.")
        sys.exit(1)

    removed = clean_docx_metadata(path, out_path)
    print(f"Wrote: {out_path}")
    if removed["core_props_cleared"]:
        print(f"  Cleared core props: {removed['core_props_cleared']}")
    if removed["app_props_cleared"]:
        print(f"  Cleared app props: {removed['app_props_cleared']}")
    if removed["custom_xml_removed"]:
        print(f"  Removed customXml parts: {removed['custom_xml_removed']}")
    if not any(removed.values()):
        print("  Nothing to clean — metadata was already blank.")
    print("\nNote: this only clears document metadata. It does not rewrite the")
    print("text itself — run 'inspect' on the output and hand-edit any flagged")
    print("cliches / uniform sentence rhythm to change the actual style signal.")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="cmd", required=True)

    p_inspect = sub.add_parser("inspect", help="Report AI-signal findings")
    p_inspect.add_argument("file")
    p_inspect.set_defaults(func=cmd_inspect)

    p_clean = sub.add_parser("clean", help="Strip docx metadata fingerprints")
    p_clean.add_argument("file")
    p_clean.add_argument("-o", "--output")
    p_clean.set_defaults(func=cmd_clean)

    args = parser.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
