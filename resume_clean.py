# Harvard's explicit DON'T list: no personal pronouns (I, We, and their forms)
PRONOUN_RE = re.compile(r"\b(I|I'm|I've|I'll|I'd|We|We're|We've|My|Our|Us|Myself|Ourselves)\b")

BULLET_START_RE = re.compile(r"^(\**\s*)([A-Z][a-zA-Z]*)")


def sentence_lengths(lines: list[str]) -> list[int]:
    lengths = []
    for line in lines:
        # crude sentence split
        sentences = re.split(r"(?<=[.!?])\s+", line)
        for s in sentences:
            words = s.split()
            if words:
                lengths.append(len(words))
    return lengths


def find_cliches(lines: list[str]) -> dict:
    hits = {}
    for line in lines:
        low = line.lower()
        for phrase in CLICHE_PHRASES:
            if phrase in low:
                hits.setdefault(phrase, []).append(line[:90])
    return hits


def bullet_opener_repetition(lines: list[str]) -> dict:
    openers = {}
    for line in lines:
        content = _content_for_check(line)
        cleaned = re.sub(r"^[\*\-\u2022\s]+", "", content)
        m = BULLET_START_RE.match(cleaned)
        if m:
            word = m.group(2)
            openers[word] = openers.get(word, 0) + 1
    # only report openers used 3+ times
    return {k: v for k, v in openers.items() if v >= 3}


def _content_for_check(line: str) -> str:
    """Bullets in this resume style are written as 'Bold Label: sentence'.
    For pronoun/verb checks we want the sentence, not the label — checking
    the label ('Data Engineering & Lakehouse:', 'Data Analyst | ...') would
    misfire on job titles and skill-category names that aren't sentences."""
    if ": " in line:
        return line.split(": ", 1)[1]
    return line


def harvard_pronoun_check(lines: list[str]) -> list[str]:
    hits = []
    for line in lines:
        content = _content_for_check(line)
        if PRONOUN_RE.search(content):
            hits.append(line[:100])
    return hits


def harvard_weak_opener_check(lines: list[str]) -> list[str]:
    """Flag bullets whose opening word isn't on Harvard's action-verb list.
    Only applied to lines that look like a 'Label: sentence' bullet, since
    job titles, company names, and section headers aren't meant to open
    with an action verb in the first place."""
    flagged = []
    for line in lines:
        if ": " not in line:
            continue  # not a bullet in this format — skip (title/header/label)
        content = line.split(": ", 1)[1]
        m = re.match(r"^([A-Za-z][a-zA-Z]*)", content)
        if not m:
            continue
        first_word = m.group(1).lower()
        if first_word not in HARVARD_ACTION_VERBS:
            flagged.append(f"'{m.group(1)}' -> \"{line[:90]}\"")
    return flagged


def burstiness_report(lines: list[str]) -> dict:
    lengths = sentence_lengths(lines)
    if len(lengths) < 3:
        return {"note": "not enough sentences to score", "n": len(lengths)}
    mean = statistics.mean(lengths)
    stdev = statistics.pstdev(lengths)
    cv = (stdev / mean) if mean else 0  # coefficient of variation
    # Human writing tends to have higher variance (cv often > 0.4-0.5).
    # Very uniform AI output often sits lower.
    flag = cv < 0.35
    return {
        "sentence_count": len(lengths),
        "mean_words_per_sentence": round(mean, 1),
        "stdev": round(stdev, 1),
        "coefficient_of_variation": round(cv, 2),
        "low_variance_flag": flag,
    }


